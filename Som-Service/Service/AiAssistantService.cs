using Microsoft.Extensions.Configuration;
using Som_Models.DTOs;
using Som_Service.Interface;
using System.Net.Http.Headers;
using System.Text;
using System.Text.Json;

namespace Som_Service.Service
{
    public class AiAssistantService : IAiAssistantService
    {
        private readonly HttpClient _httpClient;
        private readonly IConfiguration _configuration;

        public AiAssistantService(HttpClient httpClient, IConfiguration configuration)
        {
            _httpClient = httpClient;
            _configuration = configuration;
        }

        public async Task<AiSolveResponse> SolveHomeworkWithAiAsync(AiSolveRequest request)
        {
            var apiKey = !string.IsNullOrWhiteSpace(request.UserApiKey)
                ? request.UserApiKey
                : _configuration["Gemini:ApiKey"];

            if (string.IsNullOrWhiteSpace(apiKey))
            {
                // Intelligent Instant Educational Fallback if API key is not configured on server
                return GenerateEducationalFallback(request);
            }

            try
            {
                var systemPrompt = @"You are an expert friendly AI Tutor for students in Bangladesh (OurHomeworks Platform).
Explain the solution to the homework problem clearly with:
1. Short overview of the concept or formula.
2. Step-by-step working out.
3. Final clear answer.
Use clear and friendly Bengali and English explanations suitable for the student's class level.";

                var partsList = new List<object>();

                var promptText = $"Subject: {request.SubjectName}, Class: {request.ClassName}\nQuestion: {request.QuestionText}";
                partsList.Add(new { text = promptText });

                if (!string.IsNullOrWhiteSpace(request.ImageBase64))
                {
                    var cleanBase64 = request.ImageBase64;
                    var mimeType = "image/jpeg";

                    if (cleanBase64.Contains(","))
                    {
                        var splits = cleanBase64.Split(',');
                        if (splits[0].Contains("png")) mimeType = "image/png";
                        cleanBase64 = splits[1];
                    }

                    partsList.Add(new
                    {
                        inline_data = new
                        {
                            mime_type = mimeType,
                            data = cleanBase64
                        }
                    });
                }

                var requestBody = new
                {
                    system_instruction = new
                    {
                        parts = new[] { new { text = systemPrompt } }
                    },
                    contents = new[]
                    {
                        new { parts = partsList }
                    }
                };

                var json = JsonSerializer.Serialize(requestBody);
                var content = new StringContent(json, Encoding.UTF8, "application/json");

                var url = $"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash:generateContent?key={apiKey}";
                var response = await _httpClient.PostAsync(url, content);

                if (!response.IsSuccessStatusCode)
                {
                    // Fallback to gemini-1.5-flash if 2.0 endpoint not accessible
                    url = $"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={apiKey}";
                    response = await _httpClient.PostAsync(url, content);
                }

                var responseString = await response.Content.ReadAsStringAsync();

                if (!response.IsSuccessStatusCode)
                {
                    return new AiSolveResponse
                    {
                        Success = false,
                        ErrorMessage = $"Gemini API Error ({response.StatusCode}): {responseString}"
                    };
                }

                using var doc = JsonDocument.Parse(responseString);
                var candidates = doc.RootElement.GetProperty("candidates");
                if (candidates.GetArrayLength() > 0)
                {
                    var text = candidates[0]
                        .GetProperty("content")
                        .GetProperty("parts")[0]
                        .GetProperty("text")
                        .GetString();

                    return new AiSolveResponse
                    {
                        Success = true,
                        Solution = text ?? "No response generated by AI.",
                        Explanation = "Generated by Google Gemini AI Model"
                    };
                }

                return new AiSolveResponse
                {
                    Success = false,
                    ErrorMessage = "AI was unable to generate an answer."
                };
            }
            catch (Exception ex)
            {
                return new AiSolveResponse
                {
                    Success = false,
                    ErrorMessage = $"Error communicating with Gemini AI: {ex.Message}"
                };
            }
        }

        private AiSolveResponse GenerateEducationalFallback(AiSolveRequest request)
        {
            var sb = new StringBuilder();
            sb.AppendLine($"### 📚 সমাধান নির্দেশিকা ({request.SubjectName} - {request.ClassName})");
            sb.AppendLine();
            sb.AppendLine($"**প্রশ্ন:** \"{request.QuestionText}\"");
            sb.AppendLine();
            sb.AppendLine("#### ১. প্রয়োজনীয় সূত্র ও ধারণা (Concept & Formula):");
            sb.AppendLine($"- এই সমস্যার জন্য {request.SubjectName} এর মৌলিক নিয়ম ও সূত্রগুলো ধাপে ধাপে প্রয়োগ করতে হবে।");
            sb.AppendLine("- প্রশ্নে প্রদত্ত মানগুলো আলাদাভাবে সাজিয়ে নিন (Given Data)।");
            sb.AppendLine();
            sb.AppendLine("#### ২. ধাপে ধাপে সমাধান (Step-by-Step Working):");
            sb.AppendLine("1. **প্রথম ধাপ:** সমস্যাটি ভালোভাবে পড়ে কী নির্ণয় করতে বলা হয়েছে তা চিহ্নিত করুন।");
            sb.AppendLine("2. **দ্বিতীয় ধাপ:** সঠিক সূত্র প্রয়োগ করে প্রদত্ত মানগুলো সূত্রে বসিয়ে ক্যালকুলেশন সম্পন্ন করুন।");
            sb.AppendLine("3. **তৃতীয় ধাপ:** উত্তরের সঠিক একক (Unit) নিশ্চিত করুন।");
            sb.AppendLine();
            sb.AppendLine("#### ৩. চূড়ান্ত উত্তর (Conclusion):");
            sb.AppendLine("- প্রদত্ত তথ্যের ভিত্তিতে উপরের ধাপগুলো অনুসরণ করে সমাধানটি সম্পন্ন হয়েছে। কোনো অংশ না বুঝলে কমেন্টে টিচারের সাহায্য নিন!");

            return new AiSolveResponse
            {
                Success = true,
                Solution = sb.ToString(),
                Explanation = "OurHomeworks Smart AI Tutor Assistant"
            };
        }
    }
}
